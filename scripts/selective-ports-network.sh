#!/usr/bin/env bash
set -Eeuo pipefail

CONFIG="${PQTUNNEL_PORTS_CONFIG:-/etc/pqtunnel/ports.env}"
STATE="/var/lib/pqtunnel/selective-ports.state"
STATE_DIR="/var/lib/pqtunnel"
TABLE_ID=105
NFT_FAMILY=inet
NFT_TABLE=pqtunnel_ports
MARK_EGRESS=0x51
MARK_FORWARD=0x52
PRIO_EGRESS=105
PRIO_FORWARD=106

usage() {
  cat <<'USAGE'
Experimental selective-port policy routing for the IRAN/DIALER host only.

Usage:
  sudo scripts/selective-ports-network.sh status
  sudo scripts/selective-ports-network.sh validate
  sudo scripts/selective-ports-network.sh apply --confirm-dedicated-host
  sudo scripts/selective-ports-network.sh rollback

Config: /etc/pqtunnel/ports.env (or PQTUNNEL_PORTS_CONFIG)

This helper changes policy routes, TUN addresses, forwarding sysctls, and an
isolated nftables table. It never changes the main default route. It refuses
active UFW, occupied route priorities/table, pre-existing state, or an existing
PQTunnel table. Use only on a dedicated test host after reviewing the config.
Keep out-of-band/console recovery access. Rollback requires pqtunnel-client stopped.
USAGE
}
fail() { echo "selective-ports-network: $*" >&2; exit 1; }
need_root() { [[ ${EUID:-$(id -u)} -eq 0 ]] || fail 'run as root on the Iran/DIALER host'; }
valid_ifname() { [[ "$1" =~ ^[A-Za-z0-9_.:-]{1,15}$ ]]; }
valid_ip_family() { python3 -c 'import ipaddress,sys; a=ipaddress.ip_address(sys.argv[1]); sys.exit(0 if a.version == int(sys.argv[2]) and not (a.is_unspecified or a.is_multicast or a.is_loopback or a.is_link_local) else 1)' "$1" "$2" 2>/dev/null; }
valid_port() { [[ "$1" =~ ^[0-9]{1,5}$ ]] && (( 10#$1 >= 1 && 10#$1 <= 65535 )); }

mode="${1:-}"; shift || true
confirm=0
while (($#)); do
  case "$1" in
    --confirm-dedicated-host) confirm=1; shift ;;
    -h|--help) usage; exit 0 ;;
    *) fail "unknown argument: $1" ;;
  esac
done
case "$mode" in status|validate|apply|rollback) ;; -h|--help) usage; exit 0 ;; *) usage >&2; exit 2 ;; esac

if [[ "$mode" == status ]]; then
  echo "nft table $NFT_FAMILY $NFT_TABLE:"
  nft list table "$NFT_FAMILY" "$NFT_TABLE" 2>/dev/null || echo absent
  echo "IPv4 rules:"; ip -4 rule show
  echo "IPv4 route table $TABLE_ID:"; ip -4 route show table "$TABLE_ID"
  echo "IPv6 rules:"; ip -6 rule show
  echo "IPv6 route table $TABLE_ID:"; ip -6 route show table "$TABLE_ID"
  exit 0
fi

need_root
for cmd in ip nft getent awk sed grep sort stat paste python3; do command -v "$cmd" >/dev/null || fail "required command missing: $cmd"; done

if [[ "$mode" == rollback ]]; then
  [[ -f "$STATE" ]] || fail "state not found at $STATE; refusing to guess what should be removed"
  if pgrep -x pqtunnel-client >/dev/null 2>&1; then fail 'stop pqtunnel-client before rollback'; fi
  # State is generated by this script, root-owned and mode 0600.
  [[ "$(stat -c %u "$STATE")" == 0 ]] || fail 'state file is not root-owned'
  # shellcheck disable=SC1090
  source "$STATE"
  nft delete table "$NFT_FAMILY" "$NFT_TABLE" 2>/dev/null || true
  ip -4 rule del priority "$PRIO_EGRESS" fwmark "$MARK_EGRESS" lookup "$TABLE_ID" 2>/dev/null || true
  ip -4 rule del priority "$PRIO_FORWARD" fwmark "$MARK_FORWARD" lookup "$TABLE_ID" 2>/dev/null || true
  ip -6 rule del priority "$PRIO_EGRESS" fwmark "$MARK_EGRESS" lookup "$TABLE_ID" 2>/dev/null || true
  ip -6 rule del priority "$PRIO_FORWARD" fwmark "$MARK_FORWARD" lookup "$TABLE_ID" 2>/dev/null || true
  ip -4 route del default dev "$PQTUNNEL_TUN_IF" table "$TABLE_ID" 2>/dev/null || true
  ip -6 route del default dev "$PQTUNNEL_TUN_IF" table "$TABLE_ID" 2>/dev/null || true
  [[ "${ADDED_TUN4:-0}" == 1 ]] && ip -4 addr del "$PQTUNNEL_TUN_IPV4/32" dev "$PQTUNNEL_TUN_IF" 2>/dev/null || true
  if [[ "${ADDED_TUN6:-0}" == 1 && -n "${PQTUNNEL_TUN_IPV6:-}" ]]; then ip -6 addr del "$PQTUNNEL_TUN_IPV6/128" dev "$PQTUNNEL_TUN_IF" 2>/dev/null || true; fi
  if [[ "${CREATED_TUN:-0}" == 1 ]]; then ip link set dev "$PQTUNNEL_TUN_IF" down 2>/dev/null || true; ip tuntap del dev "$PQTUNNEL_TUN_IF" mode tun 2>/dev/null || true; fi
  if [[ "${CHANGED_IP_FORWARD:-0}" == 1 ]]; then sysctl -w "net.ipv4.ip_forward=$OLD_IP_FORWARD" >/dev/null; fi
  if [[ "${CHANGED_IP6_FORWARD:-0}" == 1 ]]; then sysctl -w "net.ipv6.conf.all.forwarding=$OLD_IP6_FORWARD" >/dev/null; fi
  if [[ "${WROTE_SYSCTL_FILE:-0}" == 1 && -f /etc/sysctl.d/99-pqtunnel-selective-ports.conf ]] && grep -q '^# Managed by PQTunnel selective-ports-network.sh$' /etc/sysctl.d/99-pqtunnel-selective-ports.conf; then rm -f /etc/sysctl.d/99-pqtunnel-selective-ports.conf; fi
  rm -f "$STATE"
  echo 'Selective port routes and nftables table rolled back. Main default route was not changed.'
  exit 0
fi

[[ -r "$CONFIG" ]] || fail "configuration not found: $CONFIG (copy scripts/ports.env.example first)"
[[ "$(stat -c %u "$CONFIG")" == 0 ]] || fail 'config must be owned by root'
mode_bits="$(stat -c %a "$CONFIG")"
(( (8#$mode_bits & 0022) == 0 )) || fail 'config must not be group/world writable; use chmod 0640 or stricter'
# shellcheck disable=SC1090
source "$CONFIG"
PQTUNNEL_TUN_IF="${PQTUNNEL_TUN_IF:-pqtun0}"
PQTUNNEL_TUN_IPV4="${PQTUNNEL_TUN_IPV4:-10.66.0.2}"
PQTUNNEL_TUN_IPV6="${PQTUNNEL_TUN_IPV6:-}"
PQTUNNEL_WAN_IF="${PQTUNNEL_WAN_IF:-eth0}"
PQTUNNEL_ENDPOINT="${PQTUNNEL_ENDPOINT:-}"
PQTUNNEL_ENDPOINT_PORT="${PQTUNNEL_ENDPOINT_PORT:-8443}"
PQTUNNEL_EGRESS_TCP_PORTS="${PQTUNNEL_EGRESS_TCP_PORTS:-}"
PQTUNNEL_EGRESS_UDP_PORTS="${PQTUNNEL_EGRESS_UDP_PORTS:-}"
PQTUNNEL_FORWARD_TCP="${PQTUNNEL_FORWARD_TCP:-}"
PQTUNNEL_FORWARD_UDP="${PQTUNNEL_FORWARD_UDP:-}"

valid_ifname "$PQTUNNEL_TUN_IF" || fail 'invalid TUN interface name'
valid_ifname "$PQTUNNEL_WAN_IF" || fail 'invalid WAN interface name'
valid_ip_family "$PQTUNNEL_TUN_IPV4" 4 || fail 'PQTUNNEL_TUN_IPV4 must be a valid non-special IPv4 address'
if [[ -n "$PQTUNNEL_TUN_IPV6" ]]; then valid_ip_family "$PQTUNNEL_TUN_IPV6" 6 || fail 'PQTUNNEL_TUN_IPV6 must be a valid non-special IPv6 address'; fi
valid_port "$PQTUNNEL_ENDPOINT_PORT" || fail 'invalid endpoint port'
[[ -n "$PQTUNNEL_ENDPOINT" ]] || fail 'PQTUNNEL_ENDPOINT must be a DNS name or literal IP'
command -v sysctl >/dev/null || fail 'sysctl is required'

# Return a normalized comma-separated list, rejecting invalid/empty entries.
normalize_ports() {
  local value="$1" raw n out="" seen=" "
  [[ -z "$value" ]] && { printf ''; return; }
  IFS=',' read -r -a pieces <<< "$value"
  for raw in "${pieces[@]}"; do
    n="${raw//[[:space:]]/}"
    valid_port "$n" || fail "invalid port in list: $raw"
    if [[ "$seen" != *" $n "* ]]; then out="${out:+$out,}$((10#$n))"; seen+="$n "; fi
  done
  printf '%s' "$out"
}

nft_set() { local value="$1"; printf '{ %s }' "${value//,/ , }"; }

function write_nft_rules() {
  local file="$1" ep4_list ep6_list ep4_set ep6_set egress_tcp_set egress_udp_set forward_tcp_set forward_udp_set
  ep4_set=""; ep6_set=""; ep4_list=""; ep6_list=""
  if [[ -n "$ENDPOINT4" ]]; then ep4_list="${ENDPOINT4//,/ , }"; ep4_set="set endpoint4 { type ipv4_addr; elements = { $ep4_list }; }"; fi
  if [[ -n "$ENDPOINT6" ]]; then ep6_list="${ENDPOINT6//,/ , }"; ep6_set="set endpoint6 { type ipv6_addr; elements = { $ep6_list }; }"; fi
  egress_tcp_set="$(nft_set "$EGRESS_TCP")"; egress_udp_set="$(nft_set "$EGRESS_UDP")"
  forward_tcp_set="$(nft_set "$TCP_FORWARD_PORTS")"; forward_udp_set="$(nft_set "$UDP_FORWARD_PORTS")"
  {
    echo "table inet $NFT_TABLE {"
    [[ -n "$ep4_set" ]] && echo "  $ep4_set"
    [[ -n "$ep6_set" ]] && echo "  $ep6_set"
    cat <<NFT
  chain output_mark {
    type route hook output priority mangle; policy accept;
NFT
    [[ -n "$ENDPOINT4" ]] && echo "    ip daddr @endpoint4 tcp dport $PQTUNNEL_ENDPOINT_PORT return"
    [[ -n "$ENDPOINT6" ]] && echo "    ip6 daddr @endpoint6 tcp dport $PQTUNNEL_ENDPOINT_PORT return"
    if [[ -n "$EGRESS_TCP" ]]; then
      if [[ -n "$PQTUNNEL_TUN_IPV6" ]]; then echo "    meta l4proto tcp tcp dport $egress_tcp_set ct state new ct mark set $MARK_EGRESS"; else echo "    meta nfproto ipv6 meta l4proto tcp tcp dport $egress_tcp_set drop"; echo "    meta nfproto ipv4 meta l4proto tcp tcp dport $egress_tcp_set ct state new ct mark set $MARK_EGRESS"; fi
    fi
    if [[ -n "$EGRESS_UDP" ]]; then
      if [[ -n "$PQTUNNEL_TUN_IPV6" ]]; then echo "    meta l4proto udp udp dport $egress_udp_set ct state new ct mark set $MARK_EGRESS"; else echo "    meta nfproto ipv6 meta l4proto udp udp dport $egress_udp_set drop"; echo "    meta nfproto ipv4 meta l4proto udp udp dport $egress_udp_set ct state new ct mark set $MARK_EGRESS"; fi
    fi
    echo "    ct mark $MARK_EGRESS meta mark set ct mark"
    echo '  }'
    if [[ -n "$TCP_FORWARD_RULES$UDP_FORWARD_RULES" ]]; then
      cat <<NFT
  chain prerouting_mark {
    type filter hook prerouting priority mangle; policy accept;
NFT
      if [[ -n "$TCP_FORWARD_PORTS" ]]; then echo "    iifname \"$PQTUNNEL_WAN_IF\" tcp dport $forward_tcp_set ct state new ct mark set $MARK_FORWARD meta mark set ct mark"; fi
      if [[ -n "$UDP_FORWARD_PORTS" ]]; then echo "    iifname \"$PQTUNNEL_WAN_IF\" udp dport $forward_udp_set ct state new ct mark set $MARK_FORWARD meta mark set ct mark"; fi
      echo "    iifname != \"$PQTUNNEL_TUN_IF\" ct mark $MARK_FORWARD meta mark set ct mark"
      cat <<NFT
  }
  chain prerouting_dnat {
    type nat hook prerouting priority dstnat; policy accept;
NFT
      # Avoid command substitution: it strips trailing newlines and concatenates rules.
      printf '%b' "$TCP_FORWARD_RULES"
      printf '%b' "$UDP_FORWARD_RULES"
      cat <<NFT
  }
  chain forward_policy {
    type filter hook forward priority filter; policy drop;
NFT
      echo "    iifname \"$PQTUNNEL_WAN_IF\" oifname \"$PQTUNNEL_TUN_IF\" ct mark $MARK_FORWARD ct state new,established,related accept"
      echo "    iifname \"$PQTUNNEL_TUN_IF\" oifname \"$PQTUNNEL_WAN_IF\" ct state established,related accept"
      echo '  }'
    fi
    cat <<NFT
  chain postrouting_snat {
    type nat hook postrouting priority srcnat; policy accept;
    oifname "$PQTUNNEL_TUN_IF" ip saddr != $PQTUNNEL_TUN_IPV4 snat ip to $PQTUNNEL_TUN_IPV4
NFT
    if [[ -n "$PQTUNNEL_TUN_IPV6" ]]; then echo "    oifname \"$PQTUNNEL_TUN_IF\" ip6 saddr != $PQTUNNEL_TUN_IPV6 snat ip6 to $PQTUNNEL_TUN_IPV6"; fi
    echo '  }'
    echo '}'
  } > "$file"
}

EGRESS_TCP="$(normalize_ports "$PQTUNNEL_EGRESS_TCP_PORTS")"
EGRESS_UDP="$(normalize_ports "$PQTUNNEL_EGRESS_UDP_PORTS")"

# Parse and validate forwarding mappings into nft rule lines and public-port lists.
TCP_FORWARD_RULES=""; UDP_FORWARD_RULES=""; TCP_FORWARD_PORTS=""; UDP_FORWARD_PORTS=""
parse_forwards() {
  local proto="$1" mappings="$2" item local_port target target_ip target_port kind rule
  [[ -z "$mappings" ]] && return 0
  IFS=',' read -r -a items <<< "$mappings"
  for item in "${items[@]}"; do
    [[ "$item" == *=* ]] || fail "invalid forward mapping '$item'; expected LOCAL_PORT=IP:TARGET_PORT"
    local_port="${item%%=*}"; target="${item#*=}"
    valid_port "$local_port" || fail "invalid local port in '$item'"
    if [[ "$target" =~ ^\[([^]]+)\]:([0-9]{1,5})$ ]]; then
      target_ip="${BASH_REMATCH[1]}"; target_port="${BASH_REMATCH[2]}"; kind=ip6
      [[ -n "$PQTUNNEL_TUN_IPV6" ]] || fail "IPv6 forward '$item' requires PQTUNNEL_TUN_IPV6"
      valid_ip_family "$target_ip" 6 || fail "invalid IPv6 target in '$item'"
      rule="iifname \"$PQTUNNEL_WAN_IF\" $proto dport $local_port dnat ip6 to [$target_ip]:$target_port"
    elif [[ "$target" =~ ^([0-9]{1,3}(\.[0-9]{1,3}){3}):([0-9]{1,5})$ ]]; then
      target_ip="${BASH_REMATCH[1]}"; target_port="${BASH_REMATCH[3]}"; kind=ip
      valid_ip_family "$target_ip" 4 || fail "invalid IPv4 target in '$item'"
      rule="iifname \"$PQTUNNEL_WAN_IF\" $proto dport $local_port dnat ip to $target_ip:$target_port"
    else
      fail "invalid target '$target'; use IPv4:PORT or [IPv6]:PORT (literal IP only)"
    fi
    valid_port "$target_port" || fail "invalid target port in '$item'"
    if [[ "$proto" == tcp ]]; then
      TCP_FORWARD_RULES+="    $rule\n"
      TCP_FORWARD_PORTS="${TCP_FORWARD_PORTS:+$TCP_FORWARD_PORTS,}$local_port"
    else
      UDP_FORWARD_RULES+="    $rule\n"
      UDP_FORWARD_PORTS="${UDP_FORWARD_PORTS:+$UDP_FORWARD_PORTS,}$local_port"
    fi
  done
}
parse_forwards tcp "$PQTUNNEL_FORWARD_TCP"
parse_forwards udp "$PQTUNNEL_FORWARD_UDP"

[[ -n "$EGRESS_TCP$EGRESS_UDP$TCP_FORWARD_RULES$UDP_FORWARD_RULES" ]] || fail 'configure at least one egress port or port-forward mapping'

ENDPOINT4="$(getent ahostsv4 "$PQTUNNEL_ENDPOINT" 2>/dev/null | awk '{print $1}' | sort -u | paste -sd, - || true)"
ENDPOINT6="$(getent ahostsv6 "$PQTUNNEL_ENDPOINT" 2>/dev/null | awk '{print $1}' | sort -u | paste -sd, - || true)"
[[ -n "$ENDPOINT4$ENDPOINT6" ]] || fail 'endpoint did not resolve to an IPv4/IPv6 address; check DNS or set a literal IP'

if [[ "$mode" == validate ]]; then
  TMP_RULES="$(mktemp)"; trap 'rm -f "$TMP_RULES"' EXIT
  write_nft_rules "$TMP_RULES"
  nft -c -f "$TMP_RULES"
  echo 'Configuration and nftables syntax validated; no routes, addresses, sysctls, or firewall rules were changed.'
  exit 0
fi

[[ "$confirm" == 1 ]] || fail 'apply requires --confirm-dedicated-host after reviewing the config and this script'
[[ ! -e "$STATE" ]] || fail "state exists at $STATE; inspect status and use rollback before applying again"
nft list table "$NFT_FAMILY" "$NFT_TABLE" >/dev/null 2>&1 && fail "nft table $NFT_FAMILY $NFT_TABLE already exists; refusing to overwrite it"
if command -v ufw >/dev/null && ufw status 2>/dev/null | grep -qi '^Status: active'; then fail 'UFW is active; review and integrate rules manually rather than changing its policy automatically'; fi
if [[ -n "$TCP_FORWARD_RULES$UDP_FORWARD_RULES" ]] && nft list ruleset 2>/dev/null | grep -q 'hook forward'; then fail 'an existing nftables forward base chain was detected; refusing to add another drop-policy chain'; fi
if [[ -n "$TCP_FORWARD_RULES$UDP_FORWARD_RULES" ]] && command -v iptables-save >/dev/null 2>&1 && iptables-save 2>/dev/null | grep -qE '^-A FORWARD[[:space:]]'; then fail 'existing iptables FORWARD rules were detected; review them manually first'; fi
for prio in "$PRIO_EGRESS" "$PRIO_FORWARD"; do
  ip -4 rule show | grep -Eq "^[[:space:]]*$prio:" && fail "IPv4 rule priority $prio is already used"
  ip -6 rule show | grep -Eq "^[[:space:]]*$prio:" && [[ -n "$PQTUNNEL_TUN_IPV6" ]] && fail "IPv6 rule priority $prio is already used"
done
[[ -z "$(ip -4 route show table "$TABLE_ID")" ]] || fail "IPv4 route table $TABLE_ID is not empty"
[[ -z "$(ip -6 route show table "$TABLE_ID")" ]] || fail "IPv6 route table $TABLE_ID is not empty"

CREATED_TUN=0; ADDED_TUN4=0; ADDED_TUN6=0; OLD_IP_FORWARD="$(cat /proc/sys/net/ipv4/ip_forward)"; OLD_IP6_FORWARD="$(cat /proc/sys/net/ipv6/conf/all/forwarding)"; CHANGED_IP_FORWARD=0; CHANGED_IP6_FORWARD=0; WROTE_SYSCTL_FILE=0
# The port-forward filter chain has a DROP policy. Do not attach it to a host
# that already routes any IP family, as that could disrupt unrelated forwarding.
if [[ -n "$TCP_FORWARD_RULES$UDP_FORWARD_RULES" && ( "$OLD_IP_FORWARD" != 0 || "$OLD_IP6_FORWARD" != 0 ) ]]; then
  fail 'port-forward mappings require a dedicated host with IPv4 and IPv6 forwarding currently disabled; existing router hosts need a manually reviewed firewall integration'
fi
if ! ip link show dev "$PQTUNNEL_TUN_IF" >/dev/null 2>&1; then CREATED_TUN=1; fi
if ! ip -4 addr show dev "$PQTUNNEL_TUN_IF" 2>/dev/null | grep -Fq "$PQTUNNEL_TUN_IPV4/"; then ADDED_TUN4=1; fi
if [[ -n "$PQTUNNEL_TUN_IPV6" ]] && ! ip -6 addr show dev "$PQTUNNEL_TUN_IF" 2>/dev/null | grep -Fq "$PQTUNNEL_TUN_IPV6/"; then ADDED_TUN6=1; fi
if [[ "$OLD_IP_FORWARD" == 0 && -n "$TCP_FORWARD_RULES$UDP_FORWARD_RULES" ]]; then CHANGED_IP_FORWARD=1; fi
if [[ "$OLD_IP6_FORWARD" == 0 && -n "$PQTUNNEL_TUN_IPV6" && "$PQTUNNEL_FORWARD_TCP$PQTUNNEL_FORWARD_UDP" == *"["* ]]; then CHANGED_IP6_FORWARD=1; fi
if [[ -e /etc/sysctl.d/99-pqtunnel-selective-ports.conf ]]; then fail '/etc/sysctl.d/99-pqtunnel-selective-ports.conf already exists; refusing to overwrite it'; fi

mkdir -p "$STATE_DIR"; chmod 0700 "$STATE_DIR"
cat > "$STATE" <<STATEFILE
PQTUNNEL_TUN_IF='$PQTUNNEL_TUN_IF'
PQTUNNEL_TUN_IPV4='$PQTUNNEL_TUN_IPV4'
PQTUNNEL_TUN_IPV6='$PQTUNNEL_TUN_IPV6'
CREATED_TUN='$CREATED_TUN'
ADDED_TUN4='$ADDED_TUN4'
ADDED_TUN6='$ADDED_TUN6'
OLD_IP_FORWARD='$OLD_IP_FORWARD'
OLD_IP6_FORWARD='$OLD_IP6_FORWARD'
CHANGED_IP_FORWARD='$CHANGED_IP_FORWARD'
CHANGED_IP6_FORWARD='$CHANGED_IP6_FORWARD'
WROTE_SYSCTL_FILE='$WROTE_SYSCTL_FILE'
STATEFILE
chmod 0600 "$STATE"

rollback_partial() {
  local rc=$?
  trap - ERR
  nft delete table "$NFT_FAMILY" "$NFT_TABLE" 2>/dev/null || true
  ip -4 rule del priority "$PRIO_EGRESS" fwmark "$MARK_EGRESS" lookup "$TABLE_ID" 2>/dev/null || true
  ip -4 rule del priority "$PRIO_FORWARD" fwmark "$MARK_FORWARD" lookup "$TABLE_ID" 2>/dev/null || true
  ip -6 rule del priority "$PRIO_EGRESS" fwmark "$MARK_EGRESS" lookup "$TABLE_ID" 2>/dev/null || true
  ip -6 rule del priority "$PRIO_FORWARD" fwmark "$MARK_FORWARD" lookup "$TABLE_ID" 2>/dev/null || true
  ip -4 route del default dev "$PQTUNNEL_TUN_IF" table "$TABLE_ID" 2>/dev/null || true
  ip -6 route del default dev "$PQTUNNEL_TUN_IF" table "$TABLE_ID" 2>/dev/null || true
  (( ADDED_TUN4 )) && ip -4 addr del "$PQTUNNEL_TUN_IPV4/32" dev "$PQTUNNEL_TUN_IF" 2>/dev/null || true
  if (( ADDED_TUN6 )) && [[ -n "$PQTUNNEL_TUN_IPV6" ]]; then ip -6 addr del "$PQTUNNEL_TUN_IPV6/128" dev "$PQTUNNEL_TUN_IF" 2>/dev/null || true; fi
  if (( CREATED_TUN )); then ip link set dev "$PQTUNNEL_TUN_IF" down 2>/dev/null || true; ip tuntap del dev "$PQTUNNEL_TUN_IF" mode tun 2>/dev/null || true; fi
  (( CHANGED_IP_FORWARD )) && sysctl -w "net.ipv4.ip_forward=$OLD_IP_FORWARD" >/dev/null 2>&1 || true
  (( CHANGED_IP6_FORWARD )) && sysctl -w "net.ipv6.conf.all.forwarding=$OLD_IP6_FORWARD" >/dev/null 2>&1 || true
  if [[ -f /etc/sysctl.d/99-pqtunnel-selective-ports.conf ]] && grep -q '^# Managed by PQTunnel selective-ports-network.sh$' /etc/sysctl.d/99-pqtunnel-selective-ports.conf; then rm -f /etc/sysctl.d/99-pqtunnel-selective-ports.conf; fi
  rm -f "$STATE"
  exit "$rc"
}
trap rollback_partial ERR

if (( CREATED_TUN )); then ip tuntap add dev "$PQTUNNEL_TUN_IF" mode tun; fi
if (( ADDED_TUN4 )); then ip -4 addr add "$PQTUNNEL_TUN_IPV4/32" dev "$PQTUNNEL_TUN_IF"; fi
if (( ADDED_TUN6 )); then ip -6 addr add "$PQTUNNEL_TUN_IPV6/128" dev "$PQTUNNEL_TUN_IF"; fi
ip link set dev "$PQTUNNEL_TUN_IF" up
ip -4 route add default dev "$PQTUNNEL_TUN_IF" table "$TABLE_ID"
ip -4 rule add priority "$PRIO_EGRESS" fwmark "$MARK_EGRESS" lookup "$TABLE_ID"
ip -4 rule add priority "$PRIO_FORWARD" fwmark "$MARK_FORWARD" lookup "$TABLE_ID"
if [[ -n "$PQTUNNEL_TUN_IPV6" ]]; then
  ip -6 route add default dev "$PQTUNNEL_TUN_IF" table "$TABLE_ID"
  ip -6 rule add priority "$PRIO_EGRESS" fwmark "$MARK_EGRESS" lookup "$TABLE_ID"
  ip -6 rule add priority "$PRIO_FORWARD" fwmark "$MARK_FORWARD" lookup "$TABLE_ID"
fi
if (( CHANGED_IP_FORWARD || CHANGED_IP6_FORWARD )); then
  { echo '# Managed by PQTunnel selective-ports-network.sh'; (( CHANGED_IP_FORWARD )) && echo 'net.ipv4.ip_forward=1'; (( CHANGED_IP6_FORWARD )) && echo 'net.ipv6.conf.all.forwarding=1'; } > /etc/sysctl.d/99-pqtunnel-selective-ports.conf
  chmod 0644 /etc/sysctl.d/99-pqtunnel-selective-ports.conf
  WROTE_SYSCTL_FILE=1
  (( CHANGED_IP_FORWARD )) && sysctl -w net.ipv4.ip_forward=1 >/dev/null
  (( CHANGED_IP6_FORWARD )) && sysctl -w net.ipv6.conf.all.forwarding=1 >/dev/null
  sed -i "s/^WROTE_SYSCTL_FILE=.*/WROTE_SYSCTL_FILE='1'/" "$STATE"
fi
TMP_RULES="$(mktemp)"; trap 'rm -f "$TMP_RULES"' EXIT
write_nft_rules "$TMP_RULES"
nft -c -f "$TMP_RULES"
nft -f "$TMP_RULES"
trap - ERR
rm -f "$TMP_RULES"
echo 'Selective port rules applied. The main/default route was not changed.'
echo 'WARNING: review firewall policy; this is experimental and not production-audited.'

# This function is declared after the mode dispatch intentionally; Bash resolves it at execution time.
