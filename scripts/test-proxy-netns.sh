import socketserver
import sys
host, port = sys.argv[1], int(sys.argv[2])
chunk = bytes(64 * 1024)
class Handler(socketserver.BaseRequestHandler):
    def handle(self):
        self.request.settimeout(120)
        line = bytearray()
        while len(line) < 128 and not line.endswith(b"\n"):
            part = self.request.recv(1)
            if not part:
                return
            line.extend(part)
        try:
            op, raw_size = line.decode("ascii").strip().split()
            size = int(raw_size)
            if size <= 0 or size > 64 * 1024 * 1024:
                raise ValueError("invalid transfer size")
            if op == "UPLOAD":
                remaining = size
                while remaining:
                    data = self.request.recv(min(len(chunk), remaining))
                    if not data:
                        raise ConnectionError("upload ended early")
                    remaining -= len(data)
                self.request.sendall(("OK %d\n" % size).encode("ascii"))
            elif op == "DOWNLOAD":
                remaining = size
                while remaining:
                    n = min(len(chunk), remaining)
                    self.request.sendall(chunk[:n])
                    remaining -= n
            else:
                raise ValueError("unknown operation")
            try:
                self.request.shutdown(1)
            except OSError:
                pass
        except (ValueError, ConnectionError) as exc:
            try:
                self.request.sendall(("ERR %s\n" % str(exc)).encode("ascii"))
            except OSError:
                pass
class Server(socketserver.ThreadingTCPServer):
    allow_reuse_address = True
    daemon_threads = True
with Server((host, port), Handler) as server:
    server.serve_forever(poll_interval=0.1)
PY

